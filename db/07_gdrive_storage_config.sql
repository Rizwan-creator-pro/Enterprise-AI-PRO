--------------------------------------------------------------------------------
-- Enterprise AI Hub  |  DB upgrade 07  (GOOGLE DRIVE STORAGE REST CONFIG)
--
-- PURPOSE:
-- Securely store Google Drive credentials and root folder configuration in Oracle DB.
-- The FastAPI server dynamically loads credentials via GET /engine/storage/config,
-- eliminating sensitive JSON secret files from the GitHub repository.
--
-- Run as schema AIAGENT in:
--   APEX > SQL Workshop > SQL Scripts > Upload > Run
--   or Database Actions (SQL Developer Web) > SQL > Run Script (F5)
--------------------------------------------------------------------------------
SET DEFINE OFF
SET SERVEROUTPUT ON

-- 1. Helper procedure for idempotent DDL
CREATE OR REPLACE PROCEDURE ai_ddl (p_sql IN VARCHAR2) AS
BEGIN
    EXECUTE IMMEDIATE p_sql;
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE IN (-955, -1430, -1408, -2260, -2261) THEN NULL; ELSE RAISE; END IF;
END;
/

-- 2. Create AI_STORAGE_CONFIG table
BEGIN
    ai_ddl(q'[
        CREATE TABLE ai_storage_config (
            config_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            storage_type         VARCHAR2(50) DEFAULT 'GDRIVE' NOT NULL,
            auth_type            VARCHAR2(50) DEFAULT 'SERVICE_ACCOUNT' NOT NULL,
            root_folder_id       VARCHAR2(200),
            service_account_json CLOB,
            oauth_client_id      VARCHAR2(300),
            oauth_client_secret  VARCHAR2(300),
            oauth_refresh_token  VARCHAR2(1000),
            oauth_token_json     CLOB,
            is_active            VARCHAR2(1) DEFAULT 'Y' NOT NULL,
            updated_at           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP
        )
    ]');
END;
/

-- 3. Upsert Google Drive credentials into AI_STORAGE_CONFIG
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM ai_storage_config WHERE storage_type = 'GDRIVE';
    
    IF v_count = 0 THEN
        INSERT INTO ai_storage_config (
            storage_type,
            auth_type,
            root_folder_id,
            service_account_json,
            oauth_client_id,
            oauth_client_secret,
            oauth_refresh_token,
            oauth_token_json,
            is_active
        ) VALUES (
            'GDRIVE',
            'SERVICE_ACCOUNT',
            'YOUR_GDRIVE_ROOT_FOLDER_ID',
            TO_CLOB('{}'),
            'YOUR_OAUTH_CLIENT_ID',
            'YOUR_OAUTH_CLIENT_SECRET',
            'YOUR_OAUTH_REFRESH_TOKEN',
            TO_CLOB('{}'),
            'Y'
        );
        DBMS_OUTPUT.PUT_LINE('Inserted initial Google Drive storage credentials.');
    ELSE
        UPDATE ai_storage_config
        SET root_folder_id       = 'YOUR_GDRIVE_ROOT_FOLDER_ID',
            service_account_json = TO_CLOB('{}'),
            oauth_client_id      = 'YOUR_OAUTH_CLIENT_ID',
            oauth_client_secret  = 'YOUR_OAUTH_CLIENT_SECRET',
            oauth_refresh_token  = 'YOUR_OAUTH_REFRESH_TOKEN',
            oauth_token_json     = TO_CLOB('{}'),
            is_active            = 'Y',
            updated_at           = SYSTIMESTAMP
        WHERE storage_type = 'GDRIVE';
        DBMS_OUTPUT.PUT_LINE('Updated existing Google Drive storage credentials.');
    END IF;
    COMMIT;
END;
/

-- 4. Publish ORDS REST Template & Handler for /engine/storage/config
BEGIN
    ORDS.DEFINE_TEMPLATE(
        p_module_name => 'AI',
        p_pattern     => 'storage/config'
    );

    ORDS.DEFINE_HANDLER(
        p_module_name => 'AI',
        p_pattern     => 'storage/config',
        p_method      => 'GET',
        p_source_type => 'json/collection',
        p_comments    => 'Returns active cloud storage configuration and credentials for Enterprise AI Hub.',
        p_source      =>
'SELECT config_id,
       storage_type,
       auth_type,
       root_folder_id,
       service_account_json,
       oauth_client_id,
       oauth_client_secret,
       oauth_refresh_token,
       oauth_token_json,
       is_active
FROM ai_storage_config
WHERE is_active = ''Y''
ORDER BY config_id DESC
FETCH FIRST 1 ROWS ONLY'
    );

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('SUCCESS: ORDS endpoint /engine/storage/config published.');
END;
/
